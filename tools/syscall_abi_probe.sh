#!/usr/bin/env bash
# RetroBug — measure the syscall ABI on both sides of the boundary. SPDX-License-Identifier: Apache-2.0
#
# Why a script and committed output: C07's invariant is that guest-visible errno values are ARM-EABI
# numbers, not host ones, and that the map between them is *data*. Data gets generated from a source and
# the source checked in, so that a future reader can see which rows came from a header, which from a
# kernel's return path, and which from nobody.
#
# The guest side is only executable on a device with 32-bit runtime (`abilist32` non-empty; the SM-X710
# Tab S9). The host side runs anywhere, and both are run so the divergence table is computed from two
# real binaries rather than from one plus an assumption. If only one device is attached, the arm64 half
# still lands and the file says which half is missing — a partial measurement with a label is worth more
# than a complete one with a silent gap.
#
# Usage: tools/syscall_abi_probe.sh [RB_SERIAL=<serial>]
# Output: tests/corpus/syscall-abi-arm.txt, syscall-abi-arm64.txt, syscall-abi-map.txt

set -euo pipefail
SDK="${ANDROID_HOME:-$LOCALAPPDATA/Android/Sdk}"
NDK_VER="${RB_NDK:-28.2.13676358}"
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
TC="$SDK/ndk/$NDK_VER/toolchains/llvm/prebuilt/windows-x86_64"
ADB="$SDK/platform-tools/adb.exe"
SRC="$ROOT/tests/corpus/syscall_abi.c"
OUT_DIR="$ROOT/tests/corpus"
BUILD="$ROOT/build/syscall-abi"
mkdir -p "$BUILD"

SERIAL="${RB_SERIAL:-}"
if [ -z "$SERIAL" ]; then
  n="$("$ADB" devices | awk 'NR>1 && $2=="device"' | wc -l | tr -d ' ')"
  if [ "$n" = "1" ]; then
    SERIAL="$("$ADB" devices | awk 'NR>1 && $2=="device"{print $1}')"
  else
    echo "$n devices attached; name one with RB_SERIAL=<serial>" >&2
    exit 1
  fi
fi
adb() { MSYS_NO_PATHCONV=1 "$ADB" -s "$SERIAL" "$@"; }
to_host() {
  if command -v cygpath >/dev/null 2>&1; then cygpath -w "$1"; else printf '%s' "$1"; fi
}

SYSROOT="$TC/sysroot"
# The same flags the engine lanes use, so the header set is the one the emulator will build against.
"$TC/bin/clang.exe" --target=armv7-none-linux-androideabi26 --sysroot="$SYSROOT" \
  -mthumb -mfloat-abi=softfp -mfpu=neon -Os -static -Wall -o "$BUILD/abi32" "$SRC" -Wl,--build-id=none
"$TC/bin/clang.exe" --target=aarch64-linux-android26 --sysroot="$SYSROOT" \
  -O2 -static -Wall -o "$BUILD/abi64" "$SRC" -Wl,--build-id=none

adb wait-for-device
model="$(adb shell getprop ro.product.model | tr -d '\r')"
abilist32="$(adb shell getprop ro.product.cpu.abilist32 | tr -d '\r')"
sdk="$(adb shell getprop ro.build.version.sdk | tr -d '\r')"
echo "# device=$model serial=$SERIAL abilist32=$abilist32 sdk=$sdk"

run() {  # $1 binary on device, remaining words are its arguments
  local bin="$1"; shift
  adb push "$(to_host "$BUILD/$bin")" "/data/local/tmp/$bin" >/dev/null
  adb shell "chmod 755 /data/local/tmp/$bin; /data/local/tmp/$bin $*; echo rc=\$?"
}

{
  echo "# generated by tools/syscall_abi_probe.sh on $(date -Is)"
  echo "# device=$model serial=$SERIAL sdk=$sdk abilist32=$abilist32"
  echo "# clang=$("$TC/bin/clang.exe" --version | head -1 | tr -s ' ')"
  echo "# domain=u:r:shell — see the note in syscall_abi.c on why seccomp *denial* is not measured here"
  run abi32
} > "$OUT_DIR/syscall-abi-arm.txt"

{
  echo "# generated by tools/syscall_abi_probe.sh on $(date -Is)"
  echo "# device=$model serial=$SERIAL sdk=$sdk"
  run abi64
} > "$OUT_DIR/syscall-abi-arm64.txt"

# The map, as a diff of two tables rather than as a table of recollections. The probe pads names to 18
# columns, so each row is normalised to `name value` before it is compared: a pattern expecting exactly one
# space after the name matches only the names long enough not to be padded, which is how this script's
# first version found one divergence out of fifteen and looked entirely plausible while doing so
# (`__NR_clock_gettime` is 18 characters; `EPERM` is 5).
tbl() {
  grep -E '^[A-Za-z_0-9]+ +[0-9]+ ' "$1" | awk '{print $1, $2}' | sort -k1,1
}
tbl "$OUT_DIR/syscall-abi-arm.txt" > "$BUILD/a32.tbl"
tbl "$OUT_DIR/syscall-abi-arm64.txt" > "$BUILD/a64.tbl"
{
  echo "# generated by tools/syscall_abi_probe.sh (do not edit; see the script for the derivation)"
  echo "# host side read from a $model binary. Columns: name, guest (ARM EABI), host (AArch64)."
  echo "# A row here means the same name has two different numbers, so a forwarded call has to be"
  echo "# translated by *name*, never by reusing the number."
  echo "# name                    guest   host"
  join "$BUILD/a32.tbl" "$BUILD/a64.tbl" | awk '$2 != $3 {printf "%-22s %-7s %-7s\n", $1, $2, $3}'
  echo "# defined on the guest side only (no host number: emulate or refuse, never forward)"
  comm -23 <(cut -d' ' -f1 "$BUILD/a32.tbl") <(cut -d' ' -f1 "$BUILD/a64.tbl")
  echo "# defined on the host side only (nothing in the guest ABI can reach it)"
  comm -13 <(cut -d' ' -f1 "$BUILD/a32.tbl") <(cut -d' ' -f1 "$BUILD/a64.tbl")
} > "$OUT_DIR/syscall-abi-map.txt"

echo "--- guest table (first lines)"
head -6 "$OUT_DIR/syscall-abi-arm.txt"
echo "--- divergences"
cat "$OUT_DIR/syscall-abi-map.txt"
